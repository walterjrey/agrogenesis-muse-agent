import { z } from "zod";
import { GameId, ResourceEstimate, SimTimeS, TargetRef, ValidationIssue } from "./common.js";

/**
 * Mirrors the simulator's `ManagedActionPreview` / `ActionDefinition`
 * (src/simulation/management in the AgroGenesis repo). The simulator is the only validator;
 * the agent never re-implements action rules.
 */
export const AvailableAction = z.strictObject({
  type: z.string().min(1),
  label: z.string(),
  category: z.enum(["agriculture", "machinery", "robotics", "livestock", "water", "economy"]),
  description: z.string(),
  target: TargetRef.nullable(),
  /** JSON Schema generated by the simulator from its authoritative parameter schema. */
  parametersSchema: z.record(z.string(), z.unknown()),
  preconditions: z.array(z.string()),
  constraints: z.array(z.string()),
  requiredEquipment: z.array(z.string()),
  estimate: z.strictObject({ resources: ResourceEstimate, durationS: z.number().nonnegative() }),
  eligibility: z.strictObject({ eligible: z.boolean(), issues: z.array(ValidationIssue) }),
  asynchronous: z.boolean(),
  approvalRequired: z.boolean(),
  cancellation: z.enum(["until_started", "while_running", "never"]),
});
export type AvailableAction = z.infer<typeof AvailableAction>;

export const AvailableActions = z.strictObject({
  gameId: GameId,
  revision: z.number().int().positive(),
  simTimeS: SimTimeS,
  actions: z.array(AvailableAction),
});
export type AvailableActions = z.infer<typeof AvailableActions>;
